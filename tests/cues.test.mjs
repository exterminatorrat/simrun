import test from 'node:test';
import assert from 'node:assert/strict';
import {cues,cueSheetCSV,downloadCues} from '../dist/src/cues.js';
import {defaults,simulate} from '../dist/src/model.js';
const east=[{lat:0,lon:0},{lat:0,lon:0.01}];
const corner=[{lat:0,lon:0},{lat:0,lon:0.01},{lat:0.01,lon:0.01}];
test('a right-angled route reports one turn with start and finish cues',()=>{
 const list=cues(corner);
 assert.equal(list.length,3);
 assert.equal(list[0].turn,'Start');
 assert.equal(list[0].heading,90);
 assert.equal(list[1].turn,'Turn left');
 assert.equal(list[1].heading,0);
 assert.equal(list[2].turn,'Finish');
 assert.ok(list[1].distance>0&&list[1].distance<list[2].distance);
 assert.ok(list.every((cue,i)=>i===0||cue.distance>list[i-1].distance));
});
test('a straight route and a two-point route carry no manoeuvres',()=>{
 const straight=cues([{lat:0,lon:0},{lat:0,lon:0.01},{lat:0,lon:0.02}]);
 assert.deepEqual(straight.map(c=>c.turn),['Start','Finish']);
 assert.deepEqual(cues(east).map(c=>c.turn),['Start','Finish']);
 assert.deepEqual(cues([]),[]);
});
test('reversing direction is reported as a U-turn',()=>{
 const list=cues([{lat:0,lon:0},{lat:0,lon:0.01},{lat:0,lon:0.02},{lat:0,lon:0.01}]);
 assert.equal(list.filter(c=>c.turn==='U-turn').length,1);
});
test('opposite corners distinguish left from right',()=>{
 const right=cues([{lat:0,lon:0},{lat:0.01,lon:0},{lat:0.01,lon:0.01}]);
 assert.equal(right[1].turn,'Turn right');
});
const activity=()=>{const a=defaults();a.name='Loop, "quoted"';a.path=corner;a.source='routed';return a;};
test('the cue sheet is a CSV table with a simulated-activity label',()=>{
 const a=activity(),csv=cueSheetCSV(a,simulate(a),'metric');
 const lines=csv.split('\r\n');
 assert.equal(lines[0],'SimRun cue sheet');
 assert.ok(lines.includes('Note,Simulated activity generated by SimRun; not a recorded workout.'));
 assert.equal(lines[7],'');
 assert.equal(lines[8],'#,Distance (km),Elapsed,Turn,Name,Note,Heading (deg),Latitude,Longitude,Street name');
 assert.equal(lines[9].split(',')[3],'Start');
 assert.equal(lines.at(-1),'');
 assert.ok(lines.length>=11);
});
test('the cue sheet respects units and escapes activity names',()=>{
 const a=activity(),metric=cueSheetCSV(a,simulate(a),'metric'),imperial=cueSheetCSV(a,simulate(a),'imperial');
 assert.match(metric,/Distance \(km\)/);
 assert.match(imperial,/Distance \(mi\)/);
 assert.match(metric,/Activity,"Loop, ""quoted"""/);
});
test('cue sheets cannot be exported from an unresolved draft',()=>{
 const a=activity();a.source='draft';
 assert.throws(()=>downloadCues(a,simulate(a),'metric'),/Resolve the route/);
});

test('routed street names are an additive cue-sheet column and imported routes stay blank',()=>{
 const a=activity();a.routeData={streetNames:[{start:0,end:5000,name:'Main Street'}]};
 const list=cues(a.path,25,25,a.routeData),csv=cueSheetCSV(a,simulate(a),'metric'),lines=csv.split('\r\n');
 assert.equal(list[1].streetName,'Main Street');
 assert.equal(lines[8],'#,Distance (km),Elapsed,Turn,Name,Note,Heading (deg),Latitude,Longitude,Street name');
 assert.equal(lines[9].split(',').at(-1),'Main Street');
 const imported=activity();imported.source='imported';
 assert.equal(cueSheetCSV(imported,simulate(imported),'metric').split('\r\n')[9].split(',').at(-1),'');
});

test('named stops reach the cue sheet with their name and note',()=>{
 const a=activity();a.waypoints=[{lat:0,lon:0.005,name:'Water fountain',note:'Refill, then climb'}];
 const list=cues(a.path,25,25,undefined,a.waypoints),csv=cueSheetCSV(a,simulate(a),'metric'),lines=csv.split('\r\n');
 const stop=list.find(cue=>cue.kind==='stop');
 assert.equal(stop.name,'Water fountain');
 assert.equal(stop.note,'Refill, then climb');
 assert.ok(stop.distance>0&&stop.distance<list.at(-1).distance);
 assert.deepEqual(list.map(cue=>cue.distance),[...list.map(cue=>cue.distance)].sort((x,y)=>x-y));
 const row=lines.find(line=>line.includes('Water fountain'));
 assert.ok(row.startsWith('2,'),row);
 assert.match(row,/"Refill, then climb"/);
});

test('a stop on a turn folds into the turn row instead of repeating the point',()=>{
 const a=activity();a.waypoints=[{lat:0,lon:0.01,name:'Corner shop',note:'Open until 20:00'}];
 const list=cues(corner,25,25,undefined,a.waypoints);
 assert.equal(list.length,3);
 assert.equal(list[1].turn,'Turn left');
 assert.equal(list[1].name,'Corner shop');
 assert.equal(list[1].note,'Open until 20:00');
});

test('waypoints without text add no cue-sheet rows',()=>{
 assert.equal(cues(corner,25,25,undefined,[{lat:0,lon:0.005}]).length,3);
});
